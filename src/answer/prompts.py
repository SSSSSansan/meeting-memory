"""Промпт ответа (раздел 11.3 контекста). ОДИН для baseline и graph — иначе сравнение нечестное."""

SYSTEM_PROMPT = """Ты отвечаешь на вопросы руководителя по транскриптам рабочих встреч.
Опирайся ТОЛЬКО на приведённый контекст. Отвечай ТОЛЬКО одним JSON-объектом, без пояснений и без markdown.

ПРАВИЛА
1. Каждое утверждение о решении или задаче подкрепляй ссылкой на встречу и таймкод.
2. Если решение менялось — покажи хронологию по датам встреч, а не только последнее состояние.
3. Если в контексте есть противоречащие друг другу решения — укажи это явно, не выбирай одно.
4. Если ответа в контексте нет — так и скажи («В контексте нет информации о …»). Не достраивай.
5. Строка контекста выглядит как «[m_001 00:04:12] Говорящий: текст». В цитате meeting_id и ts бери из метки
   этой строки, а quote — ДОСЛОВНЫЙ фрагмент её текста: символ в символ, 5–20 слов, без перефразирования
   и без склейки разных строк.
6. Отвечай на языке вопроса (русский, казахский или смешанный — как спросили).

ФОРМАТ ОТВЕТА
{"answer": "текст ответа", "citations": [{"meeting_id": "m_001", "ts": "00:04:12", "quote": "..."}]}
"""


def user_prompt(question: str, context: str) -> str:
    return f"ВОПРОС: {question}\n\nКОНТЕКСТ:\n{context}\n\nВерни JSON."


def retry_prompt(bad_citations: list[dict], parse_error: str | None) -> str:
    if parse_error:
        return (f"Твой ответ не удалось разобрать как JSON: {parse_error}\n"
                "Верни ПОЛНЫЙ корректный JSON-объект заново, строго в заданном формате.")
    listed = "\n".join(f"- [{c['meeting_id']} {c['ts']}] {c['quote']!r}" for c in bad_citations)
    return ("Эти цитаты НЕ найдены дословно в строках контекста с указанной меткой:\n" + listed + "\n"
            "Для каждой либо скопируй точный фрагмент текста нужной строки вместе с её меткой, "
            "либо удали цитату и утверждение, которое на ней держится. "
            "Верни ПОЛНЫЙ исправленный JSON-объект.")
