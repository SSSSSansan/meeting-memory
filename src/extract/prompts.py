WEEKDAYS = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]


def user_prompt(title: str, date: str, weekday: str, participants: list[str], transcript_text: str) -> str:
    return (
        f"Название встречи: {title}\n"
        f"Дата встречи: {date} ({weekday})\n"
        f"Участники: {', '.join(participants)}\n\n"
        f"ТРАНСКРИПТ:\n{transcript_text}\n\n"
        "Верни JSON."
    )


def retry_prompt(bad_quotes: list[str], parse_error: str | None) -> str:
    if parse_error:
        return (f"Твой ответ не удалось разобрать как JSON: {parse_error}\n"
                "Верни ПОЛНЫЙ корректный JSON-объект заново, строго в заданном формате.")
    listed = "\n".join(f"- {q!r}" for q in bad_quotes)
    return ("Эти цитаты НЕ найдены дословно в транскрипте:\n" + listed + "\n"
            "Для каждого такого пункта либо скопируй точную цитату из текста реплики, "
            "либо удали пункт, если в транскрипте его нет. "
            "Верни ПОЛНЫЙ исправленный JSON-объект.")
